  function apply(lang) {
    const locale = STRINGS[lang] ? lang : "ru";
    CGH.i18n.lang = locale;
    CGH.t = STRINGS[locale];
    CGH.i18n.localeTag = locale === "ru" ? "ru-RU" : "en-US";
    return locale;
  }

  CGH.i18n = {
    strings: STRINGS,
    lang: "ru",
    localeTag: "ru-RU",
    apply,
    async load() {
      const settings = await CGH.storage.get("settings");
      return apply(settings?.language || "ru");
    },
    async setLanguage(lang) {
      const locale = apply(lang);
      const settings = (await CGH.storage.get("settings")) || {};
      settings.language = locale;
      await CGH.storage.set({ settings });
      CGH.panel?.refresh();
      CGH.composerBar?.update();
      return locale;
    },
  };

  apply("ru");
