    async load() {
      const settings = await CGH.storage.get("settings");
      return apply(settings?.language || "ru");
    },
    async setLanguage(lang) {
      const locale = apply(lang);
      const settings = (await CGH.storage.get("settings")) || {};
      settings.language = locale;
      await CGH.storage.set({ settings });
      CGH.panel?.refresh();
      CGH.composerBar?.update();
      return locale;
    },
